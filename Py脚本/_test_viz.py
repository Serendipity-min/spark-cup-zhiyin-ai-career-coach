# 方案 D：能力雷达图（ASCII art）
# ============================================================
def radar_chart_ascii(items, max_value=10):
    print('### 方案 D：ASCII 雷达图（5维）')
    print()
    print('```')
    print('            10')
    print('            |')
    # 简化为五边形（用斜杠画外框）
    for level in range(10, 0, -2):
        row = f'{level:2d} ---'
        for label, val in items:
            if val >= level:
                row += '   ★   '
            elif val >= level - 1:
                row += '   ·   '
            else:
                row += '       '
        print(row)
    print('       ' + '   '.join([l[0] for l in items]))
    print('       ' + '   '.join([l[:3] for l, _ in items]))
    print('```')

radar_chart_ascii([
    ('专业技能', 6),
    ('项目经验', 4),
    ('工具熟练', 8),
    ('沟通表达', 7),
    ('学习能力', 9),
])
print()

