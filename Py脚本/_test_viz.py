# 方案 C：岗位匹配度热力图
# ============================================================
def heatmap_match():
    print('### 方案 C：岗位匹配度')
    print()
    print('| 能力维度 | 你的水平 | 岗位要求 | 匹配度 | 可视化 |')
    print('|---------|---------|---------|--------|--------|')
    items = [
        ('SQL', 3, 9, '30%'),
        ('Python', 7, 8, '88%'),
        ('Excel', 8, 7, '100%'),
        ('业务理解', 5, 9, '56%'),
        ('数据可视化', 4, 8, '50%'),
    ]
    for label, mine, need, pct in items:
        bar_len = int(int(pct.rstrip('%')) / 100 * 15)
        bar = '▓' * bar_len + '░' * (15 - bar_len)
        print(f'| {label} | {mine}/10 | {need}/10 | {pct} | `{bar}` |')

heatmap_match()
print()

