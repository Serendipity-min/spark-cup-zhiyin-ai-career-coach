# 方案 E：能力差距气泡矩阵
# ============================================================
def gap_matrix():
    print('### 方案 E：能力差距气泡矩阵')
    print()
    print('| 能力项 | 重要度 | 当前水平 | 差距 | 优先级标记 |')
    print('|--------|--------|---------|------|-----------|')
    items = [
        ('SQL 数据库查询', '★★★★★', 3, '巨大', '🔥 P0'),
        ('Python 数据分析', '★★★★', 7, '中等', '⚡ P1'),
        ('业务指标理解', '★★★★★', 5, '较大', '⚡ P1'),
        ('数据可视化', '★★★', 8, '小', '✓ P3'),
        ('沟通汇报', '★★★', 7, '小', '✓ P3'),
    ]
    for label, imp, cur, gap, pri in items:
        # 差距柱状图
        diff = max(0, 10 - cur)
        bar = '▼' * diff + ' ' * (10 - diff)
        print(f'| {label} | {imp} | {cur}/10 | `{bar}` | {pri} |')

gap_matrix()
