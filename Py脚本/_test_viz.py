# 方案 A：能力维度条形图（横向）
# ============================================================
def bar_chart_horizontal(items, max_width=20):
    """
    items: [(label, value 0-10), ...]
    返回 Markdown 表格 + 文本条形图
    """
    print('### 方案 A：能力维度条形图')
    print()
    print('| 能力维度 | 当前水平 | 可视化 |')
    print('|---------|---------|--------|')
    for label, value in items:
        bar = '█' * int(value / 10 * max_width) + '░' * (max_width - int(value / 10 * max_width))
        print(f'| {label} | {value}/10 | `{bar}` |')

# 测试
bar_chart_horizontal([
    ('专业技能', 6.5),
    ('项目经验', 4.0),
    ('工具熟练度', 7.5),
    ('沟通表达', 8.0),
    ('学习能力', 9.0),
    ('英语水平', 5.0),
])
print()

